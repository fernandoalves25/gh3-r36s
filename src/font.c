static const uint32_t SYMCP[] = { 0x2605, 0x2606, 0x266A, 0x2190, 0x2192, 0x2191, 0x2193, 0x2022, 0x2665, 0xBA, 0xD7, 0x2026, 0x2013, 0xA9, 0xB0, 0x2195, 0x2194, 0x2713, 0x2014 };
#define N_ASCII 95
#define N_ACC ((int)(sizeof ACCENTED / sizeof ACCENTED[0]))
#define N_SYM ((int)(sizeof SYMCP / sizeof SYMCP[0]))
#define N_ALL (N_ASCII + N_ACC + N_SYM)

static uint16_t G[N_ALL][5]; static int built = 0;
static void put_rows(uint16_t *g, const uint8_t *cols7, int top) { for (int c = 0; c < 5; c++) g[c] |= (uint16_t)(cols7[c] << top); }
static void put_art(uint16_t *g, const char *const *rows, int n, int top) { for (int r = 0; r < n; r++) for (int c = 0; c < 5; c++) if (rows[r][c] == '#') g[c] |= (uint16_t)(1 << (top + r)); }
static void put_accent(uint16_t *g, int kind, int top) {
    static const char *A[][2] = { {".....","....."}, {"...#.","..#.."}, {".#...","..#.."}, {"..#..",".#.#."}, {".#..#","#.##."}, {".....",".#.#."}, {"..#..",".##.."} };
    for (int r = 0; r < 2; r++) for (int c = 0; c < 5; c++) if (A[kind][r][c] == '#') g[c] |= (uint16_t)(1 << (top + r));
}
static void letter(uint16_t *g, char ch) {
    memset(g, 0, 5 * sizeof *g);
    if (ch >= 'a' && ch <= 'z') put_art(g, LOWER[ch - 'a'], 9, 2);
    else if (ch >= 32 && ch <= 95) put_rows(g, BASE[ch - 32], 2);
    else if (ch == '`') { static const uint8_t t[5] = {0x00,0x01,0x02,0x04,0x00}; put_rows(g, t, 2); }
    else if (ch == '{') { static const uint8_t t[5] = {0x00,0x08,0x36,0x41,0x00}; put_rows(g, t, 2); }
    else if (ch == '|') { static const uint8_t t[5] = {0x00,0x00,0x7F,0x00,0x00}; put_rows(g, t, 2); }
    else if (ch == '}') { static const uint8_t t[5] = {0x00,0x41,0x36,0x08,0x00}; put_rows(g, t, 2); }
    else if (ch == '~') { static const uint8_t t[5] = {0x08,0x04,0x08,0x10,0x08}; put_rows(g, t, 2); }
}
static void build(void) {
    for (int i = 0; i < N_ASCII; i++) letter(G[i], (char)(32 + i));
    for (int i = 0; i < N_ACC; i++) { uint16_t *g = G[N_ASCII + i]; const accent_t *a = &ACCENTED[i]; letter(g, a->base);
        int lower = a->base >= 'a';
        if (a->accent == AC_CEDIL) put_accent(g, AC_CEDIL, 9);
        else if (lower) { for (int c = 0; c < 5; c++) g[c] &= (uint16_t)~0x000F; /* the dot of the i goes */ put_accent(g, a->accent, 2); }
        else put_accent(g, a->accent, 0); }
    for (int i = 0; i < N_SYM; i++) { memset(G[N_ASCII + N_ACC + i], 0, 5 * sizeof(uint16_t)); put_rows(G[N_ASCII + N_ACC + i], SYM[i], 2); }
    built = 1;
}
int font_count(void) { return N_ALL; }
const uint16_t *font_glyph(int idx) { if (!built) build(); if (idx < 0 || idx >= N_ALL) idx = 0; return G[idx]; }
static int index_of(uint32_t cp) {
    if (cp >= 32 && cp < 127) return (int)cp - 32;
    for (int i = 0; i < N_ACC; i++) if (ACCENTED[i].cp == cp) return N_ASCII + i;
    for (int i = 0; i < N_SYM; i++) if (SYMCP[i] == cp) return N_ASCII + N_ACC + i;
    return '?' - 32;
}
int font_next(const char **s) {
    const unsigned char *p = (const unsigned char *)*s; uint32_t cp; int n;
    if (p[0] < 0x80) { cp = p[0]; n = 1; }
    else if ((p[0] & 0xE0) == 0xC0 && (p[1] & 0xC0) == 0x80) { cp = ((p[0] & 0x1Fu) << 6) | (p[1] & 0x3Fu); n = 2; }
    else if ((p[0] & 0xF0) == 0xE0 && (p[1] & 0xC0) == 0x80 && (p[2] & 0xC0) == 0x80) { cp = ((p[0] & 0x0Fu) << 12) | ((p[1] & 0x3Fu) << 6) | (p[2] & 0x3Fu); n = 3; }
    else if ((p[0] & 0xF8) == 0xF0 && (p[1] & 0xC0) == 0x80 && (p[2] & 0xC0) == 0x80 && (p[3] & 0xC0) == 0x80) { cp = ((p[0] & 0x07u) << 18) | ((p[1] & 0x3Fu) << 12) | ((p[2] & 0x3Fu) << 6) | (p[3] & 0x3Fu); n = 4; }
    else { cp = '?'; n = 1; }
    *s += n; return index_of(cp);
}
int font_strlen(const char *s) { int n = 0; while (*s) { font_next(&s); n++; } return n; }
